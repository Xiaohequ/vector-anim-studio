/// Préférence linguistique : système par défaut, avec repli anglais.
class LanguageSettings extends ChangeNotifier {
  static const String _preferenceKey = 'app_language';
  String? _selection;
  bool _loaded = false;

  bool get isLoaded => _loaded;
  String? get selection => _selection;
  String get languageCode {
    final code =
        _selection ??
        WidgetsBinding.instance.platformDispatcher.locale.languageCode;
    return const <String>{'fr', 'en', 'zh'}.contains(code) ? code : 'en';
  }

  String get selectionValue => _selection ?? 'system';
  Locale? get locale => _selection == null ? null : Locale(_selection!);

  Future<void> load() async {
    try {
      final preferences = await SharedPreferences.getInstance();
      final saved = preferences.getString(_preferenceKey);
      _selection = const <String?>{null, 'fr', 'en', 'zh'}.contains(saved)
          ? saved
          : null;
    } catch (_) {
      _selection = null;
    }
    _loaded = true;
    AppStrings.setLanguage(languageCode);
    notifyListeners();
  }

  Future<void> select(String? languageCode) async {
    assert(
      languageCode == null ||
          const <String>{'fr', 'en', 'zh'}.contains(languageCode),
    );
    _selection = languageCode;
    AppStrings.setLanguage(this.languageCode);
    notifyListeners();
    try {
      final preferences = await SharedPreferences.getInstance();
      if (languageCode == null) {
        await preferences.remove(_preferenceKey);
      } else {
        await preferences.setString(_preferenceKey, languageCode);
      }
    } catch (_) {
      // Le choix reste appliqué pendant la session si le stockage est indisponible.
    }
  }
}

